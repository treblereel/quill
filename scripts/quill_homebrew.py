#!/usr/bin/env python3
"""Generate a native Homebrew formula from verified Quill release archives."""
import argparse
import hashlib
from pathlib import Path
import re

PLATFORMS = ('macos-aarch64', 'macos-x86_64', 'linux-aarch64', 'linux-x86_64')
VERSION = r'(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)(?:\.(?:0|[1-9][0-9]*))?'


def validate_version(version):
    if not re.fullmatch(VERSION + r'(?:-[0-9A-Za-z]+(?:[.-][0-9A-Za-z]+)*)?', version):
        raise ValueError('Expected a numeric release version, optionally followed by a prerelease suffix')
    return version


def stable_version(version):
    return bool(re.fullmatch(VERSION, version))


def validate_repository(repository):
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9-]*/[A-Za-z0-9][A-Za-z0-9_.-]*', repository):
        raise ValueError('Expected a GitHub owner/repository name')
    return repository


def archive_checksum(directory, platform):
    name = f'quill-{platform}.tar.gz'
    archive = directory / name
    text = (directory / (name + '.sha256')).read_text(encoding='ascii').strip()
    match = re.fullmatch(r'([0-9a-fA-F]{64}) [ *](?:dist/|\./)?' + re.escape(name), text)
    if not match:
        raise ValueError(f'Invalid checksum file for {name}')
    digest = hashlib.sha256()
    with archive.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    if digest.hexdigest() != match[1].lower():
        raise ValueError(f'Checksum mismatch for {name}')
    return digest.hexdigest()


def render_formula(version, repository, checksums):
    validate_version(version)
    validate_repository(repository)
    if set(checksums) != set(PLATFORMS) or any(not re.fullmatch(r'[0-9a-f]{64}', value) for value in checksums.values()):
        raise ValueError('Expected one SHA-256 checksum for each supported platform')
    blocks = []
    for os_name in ('macos', 'linux'):
        lines = [f'  on_{os_name} do']
        for cpu, suffix in (('arm', 'aarch64'), ('intel', 'x86_64')):
            platform = f'{os_name}-{suffix}'
            lines.extend([f'    on_{cpu} do',
                          f'      url "https://github.com/{repository}/releases/download/v{version}/quill-{platform}.tar.gz"',
                          f'      sha256 "{checksums[platform]}"', '    end'])
        lines.append('  end')
        blocks.append('\n'.join(lines))
    return f'''# Generated by scripts/quill_homebrew.py; update from verified release archives.
class Quill < Formula
  desc "Code intelligence MCP server for JVM projects"
  homepage "https://github.com/{repository}"
  version "{version}"
  license "Apache-2.0"

{(chr(10) * 2).join(blocks)}

  # Preserve the native executable and its upstream code signature.
  skip_clean "bin/quill"

  def install
    bin.install "quill"
    doc.install "README.md"
  end

  def caveats
    <<~EOS
      Kotlin semantic analysis requires Java 17 or newer.
      Quill uses JAVA_HOME, then java on PATH; use your project's JDK.
      Run quill init in a compiled Maven or Gradle project to prepare its index
      and Kotlin compiler runtime. Homebrew installation does not initialize projects.
    EOS
  end

  test do
    assert_equal "quill #{{version}}", shell_output("#{{bin}}/quill --version").strip
    assert_match "Usage: quill", shell_output("#{{bin}}/quill --help")

    require "json"
    require "open3"
    require "timeout"
    Timeout.timeout(20) do
      Open3.popen3((bin/"quill").to_s, "--mcp", "--project", testpath.to_s, "--tools", "core") do |input, output, error, process|
        error_reader = Thread.new {{ error.read }}
        begin
          response = lambda do |id|
            loop do
              line = output.gets
              raise "MCP closed stdout before responding" unless line

              message = JSON.parse(line)
              break message if message["id"] == id
            end
          end
          input.puts JSON.generate(jsonrpc: "2.0", id: 1, method: "initialize",
                                   params: {{protocolVersion: "2025-03-26", capabilities: {{}},
                                             clientInfo: {{name: "homebrew-test", version: "1"}}}})
          input.flush
          initialized = response.call(1)
          assert_nil initialized["error"]
          assert_equal "quill", initialized.fetch("result").fetch("serverInfo").fetch("name")
          input.puts JSON.generate(jsonrpc: "2.0", method: "notifications/initialized")
          input.puts JSON.generate(jsonrpc: "2.0", id: 2, method: "tools/list", params: {{}})
          input.flush
          tools = response.call(2)
          assert_nil tools["error"]
          assert_includes tools.fetch("result").fetch("tools").map {{ |tool| tool.fetch("name") }}, "get_overview"
          input.close
          assert_predicate process.value, :success?, "MCP did not exit cleanly after EOF"
        ensure
          input.close unless input.closed?
          if process.alive?
            Process.kill("KILL", process.pid)
            process.join
          end
          error_reader.join(1)
        end
      end
    end
  end
end
'''


def check_upgrade(version, previous):
    if previous is None or not previous.exists():
        return
    matches = re.findall(r'^  version "([^"\n]+)"$', previous.read_text(encoding='utf-8'), re.MULTILINE)
    if len(matches) != 1 or not stable_version(matches[0]) or not stable_version(version):
        raise ValueError('Tap updates require explicit stable numeric versions')
    parts = lambda value: tuple(int(part) for part in value.split('.')) + (0,) * (3 - len(value.split('.')))
    if parts(version) < parts(matches[0]):
        raise ValueError(f'Refusing to downgrade tap from {matches[0]} to {version}')


def generate(version, repository, archives, output, previous=None):
    # Validate everything before replacing an existing formula.
    validate_version(version)
    validate_repository(repository)
    check_upgrade(version, previous)
    checksums = {platform: archive_checksum(archives, platform) for platform in PLATFORMS}
    formula = render_formula(version, repository, checksums)
    if previous is not None and previous.exists():
        current = previous.read_text(encoding='utf-8')
        old = re.findall(r'^  version "([^"\n]+)"$', current, re.MULTILINE)[0]
        if version == old:
            old_checksums = re.findall(r'^      sha256 "([0-9a-f]{64})"$', current, re.MULTILINE)
            if old_checksums != [checksums[platform] for platform in PLATFORMS]:
                raise ValueError('Refusing to change archive checksums for an existing release version')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(formula, encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--version', required=True)
    parser.add_argument('--repository', default='treblereel/quill')
    parser.add_argument('--archives', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--previous', type=Path, help='Existing tap formula; reject stale release downgrades')
    args = parser.parse_args()
    try:
        generate(args.version, args.repository, args.archives, args.output, args.previous)
    except (OSError, ValueError) as error:
        parser.exit(1, f'Homebrew formula generation failed: {error}\n')


if __name__ == '__main__':
    main()
