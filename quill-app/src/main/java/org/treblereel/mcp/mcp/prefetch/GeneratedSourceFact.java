package org.treblereel.mcp.mcp.prefetch;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;
import org.treblereel.mcp.core.Json;
import org.treblereel.mcp.db.ReadQueryContext;

/**
 * A class whose source a build plugin generated under target/generated-sources: the file, its
 * generator note, the plugin and inputs in the module pom, and the application classes implementing
 * it. Apollo AQ-048 (Codex): asked where ReleaseManagementApi comes from and what to change
 * instead, Codex grepped pom.xml and fetched the spec from the web.
 */
final class GeneratedSourceFact {

    private static final ObjectMapper JSON = Json.MAPPER;
    private static final Pattern PLUGIN = Pattern.compile("<plugin>(.*?)</plugin>", Pattern.DOTALL);
    private static final Pattern PROPERTY = Pattern.compile("\\$\\{([^}]+)}");
    private static final List<String> INPUTS =
            List.of(
                    "inputSpec",
                    "generatorName",
                    "sourceDirectory",
                    "schemaDirectory",
                    "protoSourceRoot",
                    "wsdlUrls");

    private GeneratedSourceFact() {}

    static ObjectNode fact(ReadQueryContext db, Path root, String className) throws IOException {
        if (root == null || className == null || !className.contains(".")) return null;
        String outer =
                className.contains("$")
                        ? className.substring(0, className.indexOf('$'))
                        : className;
        String suffix = outer.replace('.', '/') + ".java";
        Path file = null;
        for (Path generatedRoot : generatedRoots(root)) {
            try (Stream<Path> walk = Files.walk(generatedRoot, 12)) {
                file =
                        walk.filter(
                                        path ->
                                                path.toString()
                                                        .replace('\\', '/')
                                                        .endsWith("/" + suffix))
                                .findFirst()
                                .orElse(null);
            }
            if (file != null) break;
        }
        if (file == null) return null;
        String relative = root.relativize(file).toString().replace('\\', '/');
        int at = relative.indexOf("target/generated-sources/");
        String modulePath = at <= 0 ? "" : relative.substring(0, at - 1);
        String rest = relative.substring(at + "target/generated-sources/".length());
        String subdir = rest.contains("/") ? rest.substring(0, rest.indexOf('/')) : rest;

        ObjectNode fact =
                JSON.createObjectNode()
                        .put("kind", "generated_source")
                        .put("class", className)
                        .put("file", relative);
        ArrayNode note = JSON.createArrayNode();
        try (Stream<String> lines = Files.lines(file)) {
            lines.limit(40)
                    .map(line -> line.replaceFirst("^\\s*[/*]+\\s?", "").strip())
                    .filter(
                            line -> {
                                String lower = line.toLowerCase(Locale.ROOT);
                                return lower.contains("generated by")
                                        || lower.contains("do not edit");
                            })
                    .limit(3)
                    .forEach(note::add);
        }
        if (!note.isEmpty()) fact.set("generator_note", note);
        Path modulePom = root.resolve(modulePath.isEmpty() ? "pom.xml" : modulePath + "/pom.xml");
        if (Files.isRegularFile(modulePom)) plugin(root, modulePom, subdir, fact);
        ArrayNode implementations = JSON.createArrayNode();
        for (var cls : db.symbols.findAllClasses()) {
            if ("orphan_output".equals(cls.origin()) || cls.inTestSourceSet()) continue;
            if (cls.interfaces().contains(className) || className.equals(cls.superclass()))
                implementations.add(cls.className());
            if (implementations.size() == 6) break;
        }
        if (!implementations.isEmpty()) fact.set("implemented_by", implementations);
        fact.put(
                "scope_note",
                "build output under target/ (not tracked), regenerated on the next build: change the plugin's input or "
                        + "configuration, and the implementing classes, not this file");
        return fact;
    }

    private static List<Path> generatedRoots(Path root) throws IOException {
        List<Path> roots = new ArrayList<>();
        Path own = root.resolve("target/generated-sources");
        if (Files.isDirectory(own)) roots.add(own);
        try (Stream<Path> walk = Files.walk(root, 3)) {
            walk.filter(
                            path ->
                                    path.endsWith("target/generated-sources")
                                            && Files.isDirectory(path)
                                            && !path.equals(own))
                    .filter(
                            path ->
                                    !path.toString().contains("/.git/")
                                            && !path.toString().contains("/node_modules/"))
                    .forEach(roots::add);
        }
        return roots;
    }

    private static void plugin(Path root, Path pom, String subdir, ObjectNode fact)
            throws IOException {
        String text = Files.readString(pom);
        String rootPom =
                Files.isRegularFile(root.resolve("pom.xml"))
                        ? Files.readString(root.resolve("pom.xml"))
                        : "";
        Matcher plugins = PLUGIN.matcher(text);
        while (plugins.find()) {
            String block = plugins.group(1);
            if (!block.contains("generated-sources/" + subdir)) continue;
            String coordinates = tag(block, "groupId") + ":" + tag(block, "artifactId");
            String version = resolve(tag(block, "version"), text, rootPom);
            String phase = tag(block, "phase");
            fact.put(
                    "generated_by_plugin",
                    coordinates
                            + (version.isEmpty() ? "" : " " + version)
                            + " in "
                            + root.relativize(pom).toString().replace('\\', '/')
                            + (phase.isEmpty() ? "" : " at " + phase));
            ArrayNode inputs = JSON.createArrayNode();
            StringBuilder raws = new StringBuilder();
            for (String input : INPUTS) {
                String raw = tag(block, input);
                if (raw.isEmpty()) continue;
                raws.append(raw).append(' ');
                String resolved = resolve(raw, text, rootPom);
                inputs.add(input + " " + raw + (resolved.equals(raw) ? "" : " = " + resolved));
            }
            // A -Dproperty in .mvn/maven.config wins over the pom's value for every build.
            Path mavenConfig = root.resolve(".mvn/maven.config");
            if (Files.isRegularFile(mavenConfig)) {
                List<String> config = List.of(Files.readString(mavenConfig).split("\\s+"));
                Matcher property = PROPERTY.matcher(raws);
                while (property.find()) {
                    String prefix = "-D" + property.group(1) + "=";
                    for (String token : config)
                        if (token.startsWith(prefix))
                            inputs.add(
                                    property.group(1)
                                            + " overridden by .mvn/maven.config: "
                                            + token.substring(prefix.length()));
                }
            }
            if (!inputs.isEmpty()) fact.set("plugin_inputs", inputs);
            return;
        }
    }

    private static String tag(String block, String name) {
        Matcher matcher =
                Pattern.compile("<" + name + ">\\s*([^<]*?)\\s*</" + name + ">").matcher(block);
        return matcher.find() ? matcher.group(1) : "";
    }

    private static String resolve(String value, String pom, String rootPom) {
        Matcher matcher = PROPERTY.matcher(value);
        StringBuilder result = new StringBuilder();
        while (matcher.find()) {
            String property = matcher.group(1);
            String found = tag(pom, property);
            if (found.isEmpty()) found = tag(rootPom, property);
            matcher.appendReplacement(
                    result, Matcher.quoteReplacement(found.isEmpty() ? matcher.group() : found));
        }
        matcher.appendTail(result);
        return result.toString();
    }
}
